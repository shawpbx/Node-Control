function rxChannelFor(radioInterface: string, stanza: string): string {
  if (radioInterface === 'simpleusb') return `SimpleUSB/${stanza}`;
  if (radioInterface === 'usbradio') return `Radio/${stanza}`;
  return 'dahdi/pseudo';
}

function getDvSwitchPrivateNode(config: MmdvmConfiguration): string | null {
  if (!config.dvswitch.enabled) return null;
  const bn = config.dvswitch.bridgeNodeNumber.trim();
  if (!/^\d{4,6}$/.test(bn)) return null;
  const primary = config.allstar.nodeNumber.trim();
  const extras = config.allstar.additionalNodes.map((n) => n.nodeNumber.trim());
  if (bn === primary || extras.includes(bn)) return null;
  return bn;
}

