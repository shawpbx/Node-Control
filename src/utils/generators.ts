export function generateInstallScript(config: MmdvmConfiguration): string {
  const { modem, networks, allstar, dvswitch, system } = config;

  return `#!/usr/bin/env bash
# ============================================================================
# AllStarLink 3, DVSwitch & MMDVM Automated Installer
# Generated by Node Control WebGUI
# Targets: Raspberry Pi OS (Bookworm / Trixie) & Debian 12/13
# ============================================================================
set -euo pipefail

if [[ "\${EUID}" -ne 0 ]]; then
  echo "[ERROR] Run as root: sudo bash $0"
  exit 1
fi

export DEBIAN_FRONTEND=noninteractive
OS_CODENAME="$(. /etc/os-release 2>/dev/null && echo "\${VERSION_CODENAME:-bookworm}")"

echo "=== [1/6] System Dependencies, Hostname & Timezone ==="
hostnamectl set-hostname "${sanitizeIniLine(system.hostname)}" || true
timedatectl set-timezone "${sanitizeIniLine(system.timezone)}" || true

apt-get update -y
apt-get install -y --no-install-recommends \\
  git curl wget ca-certificates gnupg2 lsb-release build-essential g++ make \\
  nlohmann-json3-dev libmosquitto-dev libsamplerate0-dev

${
  allstar.enabled
    ? `echo "=== [2/6] Install AllStarLink 3 (ASL3) & Asterisk Configs ==="
if ! dpkg -s asl3 >/dev/null 2>&1; then
  ASL_DEB="asl-apt-repos.deb12_all.deb"
  if [[ "\${OS_CODENAME}" == "trixie" ]]; then
    ASL_DEB="asl-apt-repos.deb13_all.deb"
  fi
  curl -fsSL "https://repo.allstarlink.org/public/\${ASL_DEB}" -o /tmp/asl-apt-repos.deb
  dpkg -i /tmp/asl-apt-repos.deb || apt-get install -f -y
  rm -f /tmp/asl-apt-repos.deb
  apt-get update -y
  apt-get install -y asl3 asl3-asterisk asl3-menu
fi
${allstar.installAllmon3 ? 'apt-get install -y allmon3 || true' : '# Allmon3 skipped'}

mkdir -p /etc/asterisk
cat <<'EOF_RPT' > /etc/asterisk/rpt.conf
${generateRptConf(config)}EOF_RPT
cat <<'EOF_IAX' > /etc/asterisk/iax.conf
${generateIaxConf(config)}EOF_IAX
cat <<'EOF_EXT' > /etc/asterisk/extensions.conf
${generateExtensionsConf(config)}EOF_EXT
cat <<'EOF_USB' > /etc/asterisk/simpleusb.conf
${generateSimpleUsbConf(config)}EOF_USB
cat <<'EOF_MGR' > /etc/asterisk/manager.conf
${generateManagerConf(config)}EOF_MGR
chown -R asterisk:asterisk /etc/asterisk
chmod 0640 /etc/asterisk/iax.conf /etc/asterisk/manager.conf
systemctl enable --now asterisk.service
systemctl restart asterisk.service`
    : 'echo "=== [2/6] AllStarLink 3 Skipped (Disabled) ==="'
}

${
  dvswitch.enabled
    ? `echo "=== [3/6] Install DVSwitch (Analog_Bridge, MMDVM_Bridge, md380-emu) ==="
if [[ ! -f /opt/Analog_Bridge/Analog_Bridge ]]; then
  curl -fsSL http://dvswitch.org/bookworm -o /tmp/dvswitch-repo.sh
  chmod +x /tmp/dvswitch-repo.sh
  /tmp/dvswitch-repo.sh || true
  rm -f /tmp/dvswitch-repo.sh
  apt-get update -y
  apt-get install -y dvswitch-server || apt-get install -y analog-bridge mmdvm-bridge md380-emu
fi
mkdir -p /opt/Analog_Bridge /opt/MMDVM_Bridge /var/log/mmdvm
cat <<'EOF_AB' > /opt/Analog_Bridge/Analog_Bridge.ini
${generateAnalogBridgeIni(config)}EOF_AB
cat <<'EOF_DVS' > /opt/MMDVM_Bridge/DVSwitch.ini
${generateDvSwitchIni(config)}EOF_DVS
cat <<'EOF_MB' > /opt/MMDVM_Bridge/MMDVM_Bridge.ini
${generateMmdvmBridgeIni(config)}EOF_MB
chmod 0640 /opt/MMDVM_Bridge/MMDVM_Bridge.ini
for u in md380-emu analog_bridge mmdvm_bridge; do
  if systemctl list-unit-files "\${u}.service" >/dev/null 2>&1; then
    systemctl enable --now "\${u}.service" || true
    systemctl restart "\${u}.service" || true
  fi
done`
    : 'echo "=== [3/6] DVSwitch Skipped (Disabled) ==="'
}

${
  modem.enabled
    ? `echo "=== [4/6] Compile & Install g4klx/MMDVMHost ==="
if ! id -u mmdvm >/dev/null 2>&1; then
  useradd --user-group -M --system mmdvm --shell /bin/false
fi
usermod -aG dialout mmdvm || true
mkdir -p /etc/mmdvm /var/log/mmdvm

${
  modem.configurePiUart
    ? `if command -v raspi-config >/dev/null 2>&1; then
  raspi-config nonint do_serial_hw 0 || true
  raspi-config nonint do_serial_cons 1 || true
fi
BOOT_DIR=""
[[ -f /boot/firmware/config.txt ]] && BOOT_DIR="/boot/firmware"
[[ -z "\${BOOT_DIR}" && -f /boot/config.txt ]] && BOOT_DIR="/boot"
if [[ -n "\${BOOT_DIR}" ]]; then
  grep -Eq '^enable_uart=1' "\${BOOT_DIR}/config.txt" || echo 'enable_uart=1' >> "\${BOOT_DIR}/config.txt"
  if grep -qi 'Raspberry Pi 5' /proc/device-tree/model 2>/dev/null; then
    grep -Eq '^dtparam=uart0=on|^dtoverlay=uart0-pi5' "\${BOOT_DIR}/config.txt" || echo 'dtparam=uart0=on' >> "\${BOOT_DIR}/config.txt"
  else
    grep -Eq '^dtoverlay=(pi3-)?(disable|miniuart)-bt' "\${BOOT_DIR}/config.txt" || echo 'dtoverlay=disable-bt' >> "\${BOOT_DIR}/config.txt"
    systemctl disable --now hciuart.service 2>/dev/null || true
  fi
  if [[ -f "\${BOOT_DIR}/cmdline.txt" ]]; then
    sed -i -E 's/console=(serial0|ttyAMA0|ttyS0),[0-9]+ ?//g' "\${BOOT_DIR}/cmdline.txt"
  fi
  systemctl disable --now serial-getty@ttyAMA0.service serial-getty@serial0.service serial-getty@ttyS0.service 2>/dev/null || true
  echo "[INFO] Pi GPIO UART configured in \${BOOT_DIR}/config.txt (reboot required if newly added)."
fi`
    : '# Pi GPIO UART auto-configuration skipped'
}

rm -rf /usr/local/src/MMDVMHost
git clone --depth 1 https://github.com/g4klx/MMDVMHost.git /usr/local/src/MMDVMHost
make -C /usr/local/src/MMDVMHost -j"$(nproc)"
if [[ -f /usr/local/src/MMDVMHost/MMDVM-Host ]]; then
  install -m 0755 /usr/local/src/MMDVMHost/MMDVM-Host /usr/local/bin/MMDVMHost
else
  install -m 0755 /usr/local/src/MMDVMHost/MMDVMHost /usr/local/bin/MMDVMHost
fi

echo "=== [5/6] Compile & Install g4klx/DMRGateway ==="
rm -rf /usr/local/src/DMRGateway
git clone --depth 1 https://github.com/g4klx/DMRGateway.git /usr/local/src/DMRGateway
make -C /usr/local/src/DMRGateway -j"$(nproc)"
install -m 0755 /usr/local/src/DMRGateway/DMRGateway /usr/local/bin/DMRGateway

echo "=== [6/6] Write MMDVM Configs, Systemd Units & Firewall ==="
curl -fsSL "https://radioid.net/static/user.csv" -o /etc/mmdvm/DMRIds.dat || touch /etc/mmdvm/DMRIds.dat
for f in NXDN.csv RSSI.dat; do
  if [[ -f "/usr/local/src/MMDVMHost/\${f}" && ! -f "/etc/mmdvm/\${f}" ]]; then
    cp "/usr/local/src/MMDVMHost/\${f}" "/etc/mmdvm/\${f}"
  elif [[ ! -f "/etc/mmdvm/\${f}" ]]; then
    touch "/etc/mmdvm/\${f}"
  fi
done

cat <<'EOF_MMDVM_INI' > /etc/mmdvm/MMDVM.ini
${generateMmdvmIni(config)}EOF_MMDVM_INI

cat <<'EOF_DMRGW_INI' > /etc/mmdvm/DMRGateway.ini
${generateDmrGatewayIni(config)}EOF_DMRGW_INI

chown -R mmdvm:mmdvm /etc/mmdvm /var/log/mmdvm
chmod 0640 /etc/mmdvm/DMRGateway.ini

cat <<'EOF_DMRGW_SVC' > /etc/systemd/system/dmrgateway.service
${generateDmrGatewayServiceUnit()}EOF_DMRGW_SVC

cat <<'EOF_MMDVM_SVC' > /etc/systemd/system/mmdvmhost.service
${generateMmdvmServiceUnit(config)}EOF_MMDVM_SVC

touch /var/log/mmdvm/MMDVMHost.log /var/log/mmdvm/DMRGateway.log
chown -R mmdvm:mmdvm /etc/mmdvm /var/log/mmdvm

cat <<'EOF_LOGROTATE' > /etc/logrotate.d/mmdvm
/var/log/mmdvm/*.log {
    daily
    rotate 7
    missingok
    notifempty
    compress
    delaycompress
    copytruncate
    su mmdvm mmdvm
}
EOF_LOGROTATE

systemctl daemon-reload
${networks.dmrEnable ? 'systemctl enable --now dmrgateway.service\nsystemctl restart dmrgateway.service' : 'systemctl disable --now dmrgateway.service 2>/dev/null || true'}
systemctl enable --now mmdvmhost.service
systemctl restart mmdvmhost.service`
    : 'echo "=== [4-6/6] MMDVMHost & DMRGateway Skipped (Disabled) ==="'
}

${
  system.enableUfw
    ? `apt-get install -y ufw
ufw default deny incoming
ufw default allow outgoing
ufw allow ${system.sshPort}/tcp comment 'SSH'
ufw allow ${system.webguiPort}/tcp comment 'WebGUI'
${allstar.enabled ? `ufw allow ${allstar.iaxPort}/udp comment 'AllStarLink IAX2'` : ''}
${allstar.enabled && allstar.installAllmon3 ? `ufw allow 80/tcp comment 'Allmon3 HTTP'\nufw allow 443/tcp comment 'Allmon3 HTTPS'` : ''}
${modem.enabled && networks.dmrEnable ? `ufw allow ${networks.dmrMasterPort}/udp comment 'DMR Master'` : ''}
ufw --force enable`
    : '# UFW firewall configuration skipped'
}

echo ""
echo "========================================================================"
echo " Installation Complete!"
echo " Check services: systemctl status asterisk analog_bridge mmdvm_bridge dmrgateway mmdvmhost"
echo "========================================================================"
`;
}

